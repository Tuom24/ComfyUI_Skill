import { createHash } from 'node:crypto';
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { join, relative } from 'node:path';

const root=fileURLToPath(new URL('../',import.meta.url));
const ignored=new Set(['src/buildInfo.generated.ts','public/build-info.json']);
async function sourceFiles(directory) {
  const files=[];
  for(const entry of await readdir(directory,{withFileTypes:true})) {
    const path=join(directory,entry.name);
    if(entry.isDirectory())files.push(...await sourceFiles(path));
    else if(/\.(?:tsx?|css|json|svg)$/.test(entry.name)&&!entry.name.includes('.test.')&&entry.name!=='test-setup.ts')files.push(path);
  }
  return files;
}
const files=[...await sourceFiles(join(root,'src')),...await sourceFiles(join(root,'public')),...['index.html','vite.config.ts','package.json','scripts/write-build-info.mjs'].map(name=>join(root,name))];
const hash=createHash('sha256');
for(const path of files.sort()) {
  const name=relative(root,path).replaceAll('\\','/');
  if(ignored.has(name))continue;
  hash.update(name);hash.update('\0');hash.update(await readFile(path));hash.update('\0');
}
const buildId=`ui-${hash.digest('hex').slice(0,16)}`;
async function writeChanged(path,content) {
  let previous='';try{previous=await readFile(path,'utf8');}catch{}
  if(previous!==content)await writeFile(path,content,'utf8');
}
await writeChanged(join(root,'src/buildInfo.generated.ts'),`// Generated by scripts/write-build-info.mjs.\nexport const UI_BUILD_ID = '${buildId}';\n`);
await writeChanged(join(root,'public/build-info.json'),`${JSON.stringify({schema:1,buildId})}\n`);
process.stdout.write(`Interface build: ${buildId}\n`);
